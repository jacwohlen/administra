-- Award or revoke, so a corrected entry never leaves a stale badge behind.
CREATE OR REPLACE FUNCTION public.refresh_member_grade_medal_badges(p_member_id int)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
    v_has_dan boolean;
    v_medals int;
    v_gold int;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM public.member_grades mg
        JOIN public.grade_definitions gd ON gd.section = mg.section AND gd.grade = mg.grade
        WHERE mg."memberId" = p_member_id AND gd."isDan"
    ) INTO v_has_dan;

    SELECT COUNT(*)::int, COUNT(*) FILTER (WHERE medal = 'gold')::int
    INTO v_medals, v_gold
    FROM public.member_medals WHERE "memberId" = p_member_id;

    PERFORM public.set_lifetime_badge(p_member_id, 'black_belt', v_has_dan);
    PERFORM public.set_lifetime_badge(p_member_id, 'medalist', v_medals >= 1);
    PERFORM public.set_lifetime_badge(p_member_id, 'podium_5', v_medals >= 5);
    PERFORM public.set_lifetime_badge(p_member_id, 'first_gold', v_gold >= 1);
END;
$$;

CREATE OR REPLACE FUNCTION public.set_lifetime_badge(p_member_id int, p_badge_id text, p_earned boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
    IF p_earned THEN
        INSERT INTO public.member_badges ("memberId", "badgeId")
        VALUES (p_member_id, p_badge_id)
        ON CONFLICT DO NOTHING;
    ELSE
        DELETE FROM public.member_badges
        WHERE "memberId" = p_member_id AND "badgeId" = p_badge_id AND season = 0;
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION public.trigger_refresh_grade_medal_badges()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER AS $$
BEGIN
    IF current_setting('app.skip_badge_refresh', true) = 'true' THEN
        IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
    END IF;

    IF TG_OP IN ('DELETE', 'UPDATE') THEN
        PERFORM public.refresh_member_grade_medal_badges(OLD."memberId");
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        PERFORM public.refresh_member_grade_medal_badges(NEW."memberId");
    END IF;

    IF TG_OP = 'DELETE' THEN RETURN OLD; ELSE RETURN NEW; END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_badges_on_member_grade ON public.member_grades;
CREATE TRIGGER trg_badges_on_member_grade
    AFTER INSERT OR UPDATE OR DELETE ON public.member_grades
    FOR EACH ROW EXECUTE FUNCTION public.trigger_refresh_grade_medal_badges();

DROP TRIGGER IF EXISTS trg_badges_on_member_medal ON public.member_medals;
CREATE TRIGGER trg_badges_on_member_medal
    AFTER INSERT OR UPDATE OR DELETE ON public.member_medals
    FOR EACH ROW EXECUTE FUNCTION public.trigger_refresh_grade_medal_badges();

-- Full refresh covers grade and medal badges as well.
CREATE OR REPLACE FUNCTION public.refresh_all_member_badges()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER AS $$
DECLARE
    v_member record;
    v_my record;
    v_sy record;
BEGIN
    FOR v_member IN SELECT id FROM public.members LOOP
        PERFORM public.refresh_member_badges(v_member.id);
        PERFORM public.refresh_member_grade_medal_badges(v_member.id);
    END LOOP;

    FOR v_my IN
        SELECT DISTINCT "memberId" AS id, left(date, 4)::int AS y
        FROM public.logs
        WHERE "memberId" IS NOT NULL AND date ~ '^\d{4}-'
    LOOP
        PERFORM public.refresh_member_season_badges(v_my.id, v_my.y);
    END LOOP;

    FOR v_sy IN
        SELECT DISTINCT t.section, left(l.date, 4)::int AS y
        FROM public.logs l
        JOIN public.trainings t ON t.id = l."trainingId"
        WHERE t.section IS NOT NULL AND l.date ~ '^\d{4}-'
    LOOP
        PERFORM public.refresh_section_season_badges(v_sy.section, v_sy.y);
    END LOOP;
END;
$$;
