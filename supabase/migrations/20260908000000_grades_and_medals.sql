-- ---------------------------------------------------------------------------
-- 2. Gradings and medals
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.member_grades (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    "memberId" int NOT NULL,
    section text NOT NULL,
    grade text NOT NULL,
    "examDate" text NOT NULL, -- YYYY-MM-DD, like every other date in the app
    note text,
    "createdAt" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT member_grades_pkey PRIMARY KEY (id),
    CONSTRAINT member_grades_member_fkey FOREIGN KEY ("memberId") REFERENCES public.members(id) ON DELETE CASCADE,
    CONSTRAINT member_grades_grade_fkey FOREIGN KEY (section, grade) REFERENCES public.grade_definitions(section, grade),
    CONSTRAINT member_grades_unique UNIQUE ("memberId", section, grade)
);

CREATE TABLE IF NOT EXISTS public.member_medals (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    "memberId" int NOT NULL,
    "eventId" int,
    competition text NOT NULL,
    date text NOT NULL, -- YYYY-MM-DD
    section text,
    medal text NOT NULL,
    category text, -- e.g. "U18 -66 kg"
    "createdAt" timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT member_medals_pkey PRIMARY KEY (id),
    CONSTRAINT member_medals_member_fkey FOREIGN KEY ("memberId") REFERENCES public.members(id) ON DELETE CASCADE,
    CONSTRAINT member_medals_event_fkey FOREIGN KEY ("eventId") REFERENCES public.events(id) ON DELETE SET NULL,
    CONSTRAINT member_medals_medal_check CHECK (medal IN ('gold', 'silver', 'bronze')),
    CONSTRAINT member_medals_event_member_unique UNIQUE ("eventId", "memberId")
);

CREATE INDEX IF NOT EXISTS idx_member_grades_member ON public.member_grades("memberId");
CREATE INDEX IF NOT EXISTS idx_member_medals_member ON public.member_medals("memberId");
CREATE INDEX IF NOT EXISTS idx_member_medals_event ON public.member_medals("eventId");

