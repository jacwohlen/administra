-- Trainingsplanung: the TK's year plan for the adult trainings.
--
-- Until now a Google Doc: which topic each training covers through the year,
-- which trainer leads it (some trainings rotate, e.g. Monday a different
-- trainer every other week; Friday only every other week) and which dates are
-- dropped (holidays, club events).
--
--   training_plan_trainings  the trainings the TK plans (usually the adult ones)
--   training_plan_sessions   one row per training and date that has a plan:
--                            trainer, topic, notes, and whether it takes place
--   training_plan_breaks     holidays and closing days. School holidays only
--                            drop the kids' trainings, the adults train on
--                            (cancels_training false: shown for orientation);
--                            when the dojo is closed (Christmas, public
--                            holidays) every planned training in the period is
--                            dropped unless its session says otherwise
--
-- A session's "cancelled" is three-valued: null follows the breaks, true
-- drops the training, false holds it even when the dojo is closed.
--
-- The TK is the exam role 'manager' (is_exam_manager(), admins included): it
-- edits the plan. All staff read it, so trainers see when they lead and what.

CREATE TABLE public.training_plan_trainings (
  training_id smallint PRIMARY KEY REFERENCES public.trainings (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.training_plan_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  training_id smallint NOT NULL REFERENCES public.trainings (id) ON DELETE CASCADE,
  date text NOT NULL CHECK (date ~ '^\d{4}-\d{2}-\d{2}$'), -- YYYY-MM-DD like every date in the app
  trainer_id integer REFERENCES public.members (id) ON DELETE SET NULL,
  topic text,
  notes text,
  cancelled boolean,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid DEFAULT auth.uid() REFERENCES auth.users (id) ON DELETE SET NULL,
  UNIQUE (training_id, date)
);

CREATE INDEX training_plan_sessions_date_idx ON public.training_plan_sessions (date);
CREATE INDEX training_plan_sessions_trainer_id_idx ON public.training_plan_sessions (trainer_id);

CREATE TABLE public.training_plan_breaks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (btrim(title) <> ''),
  date_from text NOT NULL CHECK (date_from ~ '^\d{4}-\d{2}-\d{2}$'),
  date_to text NOT NULL CHECK (date_to ~ '^\d{4}-\d{2}-\d{2}$'),
  cancels_training boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (date_to >= date_from)
);

CREATE INDEX training_plan_breaks_dates_idx ON public.training_plan_breaks (date_from, date_to);

CREATE OR REPLACE FUNCTION public.touch_training_plan_session()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
  NEW.updated_at := now();
  NEW.updated_by := auth.uid();
  RETURN NEW;
END;
$$;

CREATE TRIGGER training_plan_sessions_touch
  BEFORE UPDATE ON public.training_plan_sessions
  FOR EACH ROW EXECUTE FUNCTION public.touch_training_plan_session();

-- ---------------------------------------------------------------------------
-- Row level security: staff read, the TK writes
-- ---------------------------------------------------------------------------
ALTER TABLE public.training_plan_trainings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_plan_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.training_plan_breaks ENABLE ROW LEVEL SECURITY;

CREATE POLICY training_plan_trainings_read ON public.training_plan_trainings
  FOR SELECT TO authenticated USING ((SELECT public.is_staff()));
CREATE POLICY training_plan_trainings_insert ON public.training_plan_trainings
  FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_exam_manager()));
CREATE POLICY training_plan_trainings_delete ON public.training_plan_trainings
  FOR DELETE TO authenticated USING ((SELECT public.is_exam_manager()));

CREATE POLICY training_plan_sessions_read ON public.training_plan_sessions
  FOR SELECT TO authenticated USING ((SELECT public.is_staff()));
CREATE POLICY training_plan_sessions_insert ON public.training_plan_sessions
  FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_exam_manager()));
CREATE POLICY training_plan_sessions_update ON public.training_plan_sessions
  FOR UPDATE TO authenticated
  USING ((SELECT public.is_exam_manager())) WITH CHECK ((SELECT public.is_exam_manager()));
CREATE POLICY training_plan_sessions_delete ON public.training_plan_sessions
  FOR DELETE TO authenticated USING ((SELECT public.is_exam_manager()));

CREATE POLICY training_plan_breaks_read ON public.training_plan_breaks
  FOR SELECT TO authenticated USING ((SELECT public.is_staff()));
CREATE POLICY training_plan_breaks_insert ON public.training_plan_breaks
  FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_exam_manager()));
CREATE POLICY training_plan_breaks_update ON public.training_plan_breaks
  FOR UPDATE TO authenticated
  USING ((SELECT public.is_exam_manager())) WITH CHECK ((SELECT public.is_exam_manager()));
CREATE POLICY training_plan_breaks_delete ON public.training_plan_breaks
  FOR DELETE TO authenticated USING ((SELECT public.is_exam_manager()));

-- ---------------------------------------------------------------------------
-- Privileges
-- ---------------------------------------------------------------------------
REVOKE ALL ON public.training_plan_trainings, public.training_plan_sessions,
  public.training_plan_breaks FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.training_plan_trainings,
  public.training_plan_sessions, public.training_plan_breaks TO authenticated;
GRANT ALL ON public.training_plan_trainings, public.training_plan_sessions,
  public.training_plan_breaks TO service_role;

REVOKE EXECUTE ON FUNCTION public.touch_training_plan_session() FROM PUBLIC, anon, authenticated;
