-- Daten-Assistent: usage log and daily limits for /api/assistant
-- (docs/AI_ASSISTANT.md).
--
-- The assistant has Claude transcribe a photo, PDF or pasted text into a
-- proposal (grades from a Judo pass, an attendance list, a training plan,
-- a lesson plan, club dates). The model writes nothing: the endpoint only
-- returns the proposal, and the browser saves what the user confirmed
-- through the normal tables under RLS.
--
-- Every extraction costs money, so the endpoint first calls
-- ai_import_begin(kind), which
--
--   * checks that the account may write what it extracts (is_writer() for
--     grades, attendance, lesson plans and dates; is_exam_manager() for the
--     training plan) — the same predicates as the target tables' RLS;
--   * enforces AI_MAX_PER_USER extractions per account and AI_MAX_PER_CLUB
--     for everybody within 24 hours (SQLSTATE 'PT429', HTTP 429);
--   * logs the request in ai_imports.
--
-- ai_import_finish() records the outcome and the token usage. ai_imports
-- holds no content: no images, no names, no model output.

CREATE TABLE public.ai_imports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  kind text NOT NULL
    CHECK (kind IN ('grades', 'attendance', 'training_plan', 'lesson_plan', 'events')),
  status text NOT NULL DEFAULT 'started'
    CHECK (status IN ('started', 'ok', 'failed', 'refused')),
  input_tokens integer,
  output_tokens integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz
);

COMMENT ON TABLE public.ai_imports IS
  'One extraction of the Daten-Assistent (/api/assistant): who, what kind, outcome, tokens. No content.';

CREATE INDEX ai_imports_user_created_idx ON public.ai_imports (user_id, created_at DESC);
CREATE INDEX ai_imports_created_idx ON public.ai_imports (created_at DESC);

ALTER TABLE public.ai_imports ENABLE ROW LEVEL SECURITY;

-- Everyone sees their own usage, admins everybody's. Rows are only written
-- by the functions below.
CREATE POLICY ai_imports_read ON public.ai_imports
  FOR SELECT TO authenticated
  USING (user_id = (SELECT auth.uid()) OR (SELECT public.is_admin()));

REVOKE ALL ON public.ai_imports FROM anon, authenticated;
GRANT SELECT ON public.ai_imports TO authenticated;
GRANT ALL ON public.ai_imports TO service_role;

-- Limits, shared by ai_import_begin() and ai_import_remaining(). Onboarding
-- a club means a few dozen passes and lists on one evening; raise these in
-- a new migration if real work hits them.
CREATE OR REPLACE FUNCTION public.ai_import_limits(OUT per_user integer, OUT per_club integer)
LANGUAGE sql
IMMUTABLE
SET search_path = public
AS $$
  SELECT 60, 300;
$$;

-- Extractions the calling account has left within the last 24 hours.
CREATE OR REPLACE FUNCTION public.ai_import_remaining()
RETURNS integer
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_limits record;
  v_mine integer;
  v_club integer;
BEGIN
  IF v_uid IS NULL OR NOT (public.is_writer() OR public.is_exam_manager()) THEN
    RETURN 0;
  END IF;
  SELECT * INTO v_limits FROM public.ai_import_limits();
  SELECT count(*) INTO v_mine FROM public.ai_imports
    WHERE user_id = v_uid AND created_at > now() - interval '24 hours';
  SELECT count(*) INTO v_club FROM public.ai_imports
    WHERE created_at > now() - interval '24 hours';
  RETURN greatest(0, least(v_limits.per_user - v_mine, v_limits.per_club - v_club));
END;
$$;

-- Starts an extraction: role check, limits, log row. Returns the row id
-- for ai_import_finish() and how many extractions are left afterwards.
CREATE OR REPLACE FUNCTION public.ai_import_begin(p_kind text)
RETURNS TABLE (id bigint, remaining integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_limits record;
  v_mine integer;
  v_club integer;
  v_id bigint;
BEGIN
  IF p_kind IS NULL
     OR p_kind NOT IN ('grades', 'attendance', 'training_plan', 'lesson_plan', 'events') THEN
    RAISE EXCEPTION 'invalid kind' USING ERRCODE = '22023';
  END IF;
  -- The same predicates as the RLS of the tables the proposal is saved to
  IF v_uid IS NULL
     OR (p_kind = 'training_plan' AND NOT public.is_exam_manager())
     OR (p_kind <> 'training_plan' AND NOT public.is_writer()) THEN
    RAISE EXCEPTION 'NOT_ALLOWED' USING ERRCODE = '42501';
  END IF;

  -- Serialize so concurrent requests cannot all pass the limits at once.
  -- Held until the transaction ends.
  PERFORM pg_advisory_xact_lock(hashtext('public.ai_import_begin'));

  SELECT * INTO v_limits FROM public.ai_import_limits();

  SELECT count(*) INTO v_mine FROM public.ai_imports a
    WHERE a.user_id = v_uid AND a.created_at > now() - interval '24 hours';
  SELECT count(*) INTO v_club FROM public.ai_imports a
    WHERE a.created_at > now() - interval '24 hours';
  IF v_mine >= v_limits.per_user OR v_club >= v_limits.per_club THEN
    RAISE EXCEPTION 'too many extractions, try again tomorrow' USING ERRCODE = 'PT429';
  END IF;

  INSERT INTO public.ai_imports (user_id, kind) VALUES (v_uid, p_kind)
    RETURNING ai_imports.id INTO v_id;

  RETURN QUERY SELECT v_id,
    greatest(0, least(v_limits.per_user - v_mine - 1, v_limits.per_club - v_club - 1));
END;
$$;

-- Records the outcome of the caller's own, still running extraction.
CREATE OR REPLACE FUNCTION public.ai_import_finish(
  p_id bigint,
  p_status text,
  p_input_tokens integer DEFAULT NULL,
  p_output_tokens integer DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF p_status IS NULL OR p_status NOT IN ('ok', 'failed', 'refused') THEN
    RAISE EXCEPTION 'invalid status' USING ERRCODE = '22023';
  END IF;
  UPDATE public.ai_imports
     SET status = p_status,
         input_tokens = CASE WHEN p_input_tokens >= 0 THEN p_input_tokens END,
         output_tokens = CASE WHEN p_output_tokens >= 0 THEN p_output_tokens END,
         finished_at = now()
   WHERE ai_imports.id = p_id
     AND user_id = auth.uid()
     AND status = 'started';
END;
$$;

-- New functions are executable by anon through the default privileges
-- (20260915130000_explicit_api_role_grants.sql); these are for signed-in
-- accounts only.
REVOKE EXECUTE ON FUNCTION public.ai_import_limits() FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.ai_import_remaining() FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.ai_import_begin(text) FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.ai_import_finish(bigint, text, integer, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.ai_import_limits() TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.ai_import_remaining() TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.ai_import_begin(text) TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.ai_import_finish(bigint, text, integer, integer)
  TO authenticated, service_role;
